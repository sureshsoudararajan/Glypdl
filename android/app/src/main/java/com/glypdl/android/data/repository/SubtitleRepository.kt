package com.glypdl.android.data.repository

import android.content.Context
import com.glypdl.android.data.local.dao.SubtitleDao
import com.glypdl.android.data.local.entity.SubtitleFileEntity
import com.glypdl.android.data.model.SubtitleFile
import com.glypdl.android.util.StorageHelper
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Repository providing abstraction and operations for downloaded and saved subtitle files.
 */
@Singleton
class SubtitleRepository @Inject constructor(
    private val subtitleDao: SubtitleDao,
    @ApplicationContext private val context: Context
) {

    fun getAllSubtitles(): Flow<List<SubtitleFile>> {
        return subtitleDao.getAllSubtitles().map { list ->
            list.map { it.toModel() }
        }
    }

    suspend fun getSubtitleById(id: Long): SubtitleFile? {
        return subtitleDao.getSubtitleById(id)?.toModel()
    }

    fun getSubtitlesForDownload(downloadId: String): Flow<List<SubtitleFile>> {
        return subtitleDao.getSubtitlesForDownload(downloadId).map { list ->
            list.map { it.toModel() }
        }
    }

    suspend fun getSubtitlesForDownloadSync(downloadId: String): List<SubtitleFile> {
        return subtitleDao.getSubtitlesForDownloadSync(downloadId).map { it.toModel() }
    }

    fun searchSubtitles(query: String): Flow<List<SubtitleFile>> {
        return subtitleDao.searchSubtitles(query).map { list ->
            list.map { it.toModel() }
        }
    }

    suspend fun insertSubtitle(subtitle: SubtitleFile): Long {
        return subtitleDao.insert(subtitle.toEntity())
    }

    suspend fun insertSubtitles(subtitles: List<SubtitleFile>): List<Long> {
        return subtitleDao.insertAll(subtitles.map { it.toEntity() })
    }

    suspend fun deleteSubtitle(id: Long, deleteFileFromDisk: Boolean = true): Boolean {
        val entity = subtitleDao.getSubtitleById(id) ?: return false
        var diskDeleted = true
        if (deleteFileFromDisk) {
            val uriOrPath = entity.fileUri.ifBlank { entity.filePath ?: "" }
            diskDeleted = StorageHelper.deleteFileFromStorage(context, uriOrPath)
        }
        subtitleDao.deleteById(id)
        return diskDeleted
    }

    suspend fun deleteSubtitlesForDownload(downloadId: String, deleteFileFromDisk: Boolean = true) {
        val subtitles = subtitleDao.getSubtitlesForDownloadSync(downloadId)
        if (deleteFileFromDisk) {
            for (sub in subtitles) {
                val uriOrPath = sub.fileUri.ifBlank { sub.filePath ?: "" }
                StorageHelper.deleteFileFromStorage(context, uriOrPath)
            }
        }
        subtitleDao.deleteByDownloadId(downloadId)
    }

    fun getSubtitleCount(): Flow<Int> = subtitleDao.getSubtitleCount()

    private fun SubtitleFileEntity.toModel(): SubtitleFile {
        return SubtitleFile(
            id = id,
            downloadId = downloadId,
            mediaTitle = mediaTitle,
            mediaUrl = mediaUrl,
            languageCode = languageCode,
            languageName = languageName,
            format = format,
            isAutoGenerated = subtitleType.equals("AUTOMATIC", ignoreCase = true),
            contentUri = fileUri,
            filePath = filePath,
            fileName = fileName,
            fileSize = sizeBytes,
            createdAt = createdAt,
            isEmbedded = isEmbedded
        )
    }

    private fun SubtitleFile.toEntity(): SubtitleFileEntity {
        return SubtitleFileEntity(
            id = id,
            downloadId = downloadId,
            mediaTitle = mediaTitle,
            mediaUrl = mediaUrl,
            languageCode = languageCode,
            languageName = languageName,
            format = format,
            subtitleType = if (isAutoGenerated) "AUTOMATIC" else "MANUAL",
            fileUri = contentUri,
            filePath = filePath,
            fileName = fileName,
            sizeBytes = fileSize,
            createdAt = if (createdAt > 0) createdAt else System.currentTimeMillis(),
            isEmbedded = isEmbedded
        )
    }
}
