package com.glypdl.android.service.auth

import android.content.Context
import android.net.Uri
import dagger.hilt.android.qualifiers.ApplicationContext
import java.io.File
import java.io.FileWriter
import java.util.Locale
import javax.inject.Inject
import javax.inject.Singleton

data class AuthPlatform(
    val id: String,
    val name: String,
    val domain: String,
    val loginUrl: String
)

@Singleton
class AuthCookieManager @Inject constructor(
    @ApplicationContext private val context: Context
) {
    private val cookiesDir = File(context.filesDir, "cookies").apply {
        if (!exists()) mkdirs()
    }

    companion object {
        val SUPPORTED_PLATFORMS = listOf(
            AuthPlatform(
                id = "instagram",
                name = "Instagram",
                domain = "instagram.com",
                loginUrl = "https://www.instagram.com/accounts/login/"
            ),
            AuthPlatform(
                id = "facebook",
                name = "Facebook",
                domain = "facebook.com",
                loginUrl = "https://www.facebook.com/login/"
            ),
            AuthPlatform(
                id = "youtube",
                name = "YouTube / Google",
                domain = "youtube.com",
                loginUrl = "https://accounts.google.com/ServiceLogin?service=youtube"
            ),
            AuthPlatform(
                id = "tiktok",
                name = "TikTok",
                domain = "tiktok.com",
                loginUrl = "https://www.tiktok.com/login"
            ),
            AuthPlatform(
                id = "twitter",
                name = "X (Twitter)",
                domain = "twitter.com",
                loginUrl = "https://twitter.com/i/flow/login"
            )
        )
    }

    fun resolveDomainKey(urlOrHost: String): String {
        val host = try {
            val uri = Uri.parse(if (urlOrHost.contains("://")) urlOrHost else "https://$urlOrHost")
            uri.host ?: urlOrHost
        } catch (e: Exception) {
            urlOrHost
        }.lowercase(Locale.ROOT)

        return when {
            host.contains("instagram.com") || host.contains("instagr.am") -> "instagram.com"
            host.contains("youtube.com") || host.contains("youtu.be") -> "youtube.com"
            host.contains("tiktok.com") -> "tiktok.com"
            host.contains("twitter.com") || host.contains("x.com") -> "twitter.com"
            host.contains("facebook.com") || host.contains("fb.watch") || host.contains("fb.com") -> "facebook.com"
            else -> {
                val parts = host.split(".")
                if (parts.size >= 2) {
                    "${parts[parts.size - 2]}.${parts[parts.size - 1]}"
                } else {
                    host
                }
            }
        }
    }

    fun saveCookies(domainKey: String, rawCookies: String): Boolean {
        if (rawCookies.isBlank()) return false

        val cookieFile = File(cookiesDir, "${domainKey}.txt")
        try {
            val trimmedInput = rawCookies.trim()
            if (trimmedInput.startsWith("# Netscape HTTP Cookie File") || trimmedInput.startsWith("# HTTP Cookie File")) {
                cookieFile.writeText(trimmedInput)
                return isValidCookieFile(cookieFile)
            }

            val dotDomain = if (domainKey.startsWith(".")) domainKey else ".$domainKey"

            FileWriter(cookieFile, false).use { writer ->
                writer.write("# Netscape HTTP Cookie File\n")
                writer.write("# https://curl.se/docs/http-cookies.html\n")
                writer.write("# Generated by Glypdl. Do not edit.\n\n")

                val seenKeys = mutableSetOf<String>()
                val pairs = rawCookies.split(";").map { it.trim() }
                for (pair in pairs) {
                    if (pair.isBlank() || !pair.contains("=")) continue
                    val name = pair.substringBefore("=").trim()
                    val value = pair.substringAfter("=").trim()
                    if (name.isNotEmpty() && seenKeys.add(name)) {
                        // Standard Netscape format uses expiry 0 for session cookies
                        val isSession = name.equals("sessionid", ignoreCase = true) ||
                                       name.equals("c_user", ignoreCase = true) ||
                                       name.equals("xs", ignoreCase = true) ||
                                       name.equals("ds_user_id", ignoreCase = true)
                        val expiry = if (isSession) 0L else (System.currentTimeMillis() / 1000) + (30L * 24 * 3600)

                        writer.write("$dotDomain\tTRUE\t/\tTRUE\t$expiry\t$name\t$value\n")
                        if (domainKey.contains("instagram")) {
                            writer.write(".i.instagram.com\tTRUE\t/\tTRUE\t$expiry\t$name\t$value\n")
                            writer.write(".www.instagram.com\tTRUE\t/\tTRUE\t$expiry\t$name\t$value\n")
                            writer.write("i.instagram.com\tFALSE\t/\tTRUE\t$expiry\t$name\t$value\n")
                            writer.write("www.instagram.com\tFALSE\t/\tTRUE\t$expiry\t$name\t$value\n")
                        }
                    }
                }
            }
            return isValidCookieFile(cookieFile)
        } catch (e: Exception) {
            return false
        }
    }

    fun isValidCookieFile(file: File?): Boolean {
        if (file == null || !file.exists() || file.length() == 0L) return false
        return try {
            file.bufferedReader().use { reader ->
                var hasHeader = false
                var hasValidCookie = false
                var count = 0
                for (line in reader.lineSequence()) {
                    count++
                    if (count > 500) break
                    val trimmed = line.trim()
                    if (trimmed.startsWith("# Netscape HTTP Cookie File") || trimmed.startsWith("# HTTP Cookie File")) {
                        hasHeader = true
                    }
                    if (!trimmed.startsWith("#") && trimmed.isNotEmpty()) {
                        val fields = trimmed.split("\t")
                        if (fields.size >= 7) {
                            hasValidCookie = true
                        }
                    }
                }
                hasHeader && hasValidCookie
            }
        } catch (e: Exception) {
            false
        }
    }

    fun getCookieFile(urlOrDomain: String): File? {
        val key = resolveDomainKey(urlOrDomain)
        val file = File(cookiesDir, "${key}.txt")
        return if (isValidCookieFile(file)) file else null
    }

    fun hasCookies(domainKey: String): Boolean {
        return getCookieFile(domainKey) != null
    }

    fun hasValidCookies(domainKey: String): Boolean {
        return isValidCookieFile(getCookieFile(domainKey))
    }

    fun clearCookies(domainKey: String): Boolean {
        val file = File(cookiesDir, "${domainKey}.txt")
        return if (file.exists()) file.delete() else true
    }

    fun clearAllCookies() {
        cookiesDir.listFiles()?.forEach { it.delete() }
    }

    fun getSavedDomains(): List<String> {
        return cookiesDir.listFiles()
            ?.filter { it.isFile && it.extension == "txt" && it.length() > 0 }
            ?.map { it.nameWithoutExtension }
            ?.sorted()
            ?: emptyList()
    }
}
