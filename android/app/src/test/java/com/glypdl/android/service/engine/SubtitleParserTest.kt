package com.glypdl.android.service.engine

import com.glypdl.android.data.model.SubtitleType
import org.json.JSONObject
import org.junit.Assert.*
import org.junit.Test

class SubtitleParserTest {

    @Test
    fun testParseManualSubtitles() {
        val jsonStr = """
            {
                "subtitles": {
                    "en": [
                        {"ext": "vtt", "url": "https://example.com/en.vtt", "name": "English"},
                        {"ext": "srv3", "url": "https://example.com/en.srv3", "name": "English"}
                    ],
                    "es": [
                        {"ext": "vtt", "url": "https://example.com/es.vtt", "name": "Spanish"}
                    ],
                    "live_chat": [
                        {"ext": "json", "url": "https://example.com/chat.json"}
                    ]
                }
            }
        """.trimIndent()

        val json = JSONObject(jsonStr)
        val tracks = SubtitleParser.parseManualSubtitles(json)

        assertEquals(2, tracks.size)
        // Live chat must be excluded
        assertFalse(tracks.any { it.languageCode == "live_chat" })

        val enTrack = tracks.find { it.languageCode == "en" }
        assertNotNull(enTrack)
        assertEquals("English", enTrack?.languageName)
        assertEquals(SubtitleType.MANUAL, enTrack?.type)
        assertEquals(listOf("vtt", "srv3"), enTrack?.formats)
        assertEquals("https://example.com/en.vtt", enTrack?.url)

        val esTrack = tracks.find { it.languageCode == "es" }
        assertNotNull(esTrack)
        assertEquals("Spanish", esTrack?.languageName)
        assertEquals(listOf("vtt"), esTrack?.formats)
    }

    @Test
    fun testParseAutomaticCaptions() {
        val jsonStr = """
            {
                "automatic_captions": {
                    "fr": [
                        {"ext": "vtt", "url": "https://example.com/fr.vtt", "name": "French (auto-generated)"}
                    ],
                    "de": [
                        {"ext": "vtt", "url": "https://example.com/de.vtt", "name": "German (auto-generated)"}
                    ]
                }
            }
        """.trimIndent()

        val json = JSONObject(jsonStr)
        val tracks = SubtitleParser.parseAutomaticCaptions(json)

        assertEquals(2, tracks.size)
        assertTrue(tracks.all { it.type == SubtitleType.AUTOMATIC })
        assertTrue(tracks.all { it.isAutoGenerated })

        val fr = tracks.find { it.languageCode == "fr" }
        assertNotNull(fr)
        assertEquals("French (auto-generated)", fr?.languageName)
    }

    @Test
    fun testAutomaticCaptionsPrefersOrigOverTranslated() {
        val jsonStr = """
            {
                "automatic_captions": {
                    "ta-orig": [
                        {"ext": "vtt", "url": "https://example.com/ta-orig.vtt", "name": "Tamil (original)"}
                    ],
                    "ta": [
                        {"ext": "vtt", "url": "https://example.com/ta-translated.vtt", "name": "Tamil"}
                    ],
                    "en": [
                        {"ext": "vtt", "url": "https://example.com/en.vtt", "name": "English"}
                    ]
                }
            }
        """.trimIndent()

        val json = JSONObject(jsonStr)
        val tracks = SubtitleParser.parseAutomaticCaptions(json)

        // ta-orig and en should be present; translated ta must be skipped to avoid 429 translation errors
        assertEquals(2, tracks.size)
        assertTrue(tracks.any { it.languageCode == "ta-orig" })
        assertFalse(tracks.any { it.languageCode == "ta" })
        assertTrue(tracks.any { it.languageCode == "en" })
    }

    @Test
    fun testNullAndEmptyJson() {
        assertTrue(SubtitleParser.parseManualSubtitles(null).isEmpty())
        assertTrue(SubtitleParser.parseAutomaticCaptions(null).isEmpty())

        val emptyJson = JSONObject("{}")
        assertTrue(SubtitleParser.parseManualSubtitles(emptyJson).isEmpty())
        assertTrue(SubtitleParser.parseAutomaticCaptions(emptyJson).isEmpty())
    }

    @Test
    fun testDuplicateLanguagesMerging() {
        val jsonStr = """
            {
                "subtitles": {
                    "en": [
                        {"ext": "vtt", "url": "https://example.com/1.vtt", "name": "English"}
                    ]
                }
            }
        """.trimIndent()

        val json = JSONObject(jsonStr)
        val tracks = SubtitleParser.parseManualSubtitles(json)
        assertEquals(1, tracks.size)
        assertEquals(listOf("vtt"), tracks[0].formats)
    }

    @Test
    fun testResolveLanguageNameFallback() {
        // Fallback to Locale when name is missing
        val nameEn = SubtitleParser.resolveLanguageName("en", null)
        assertTrue(nameEn.isNotBlank())
        assertFalse(nameEn == "en") // Should be English (or locale display name)

        val nameTa = SubtitleParser.resolveLanguageName("ta", "")
        assertTrue(nameTa.isNotBlank())
    }

    @Test
    fun testParseAllSubtitlesCombined() {
        val jsonStr = """
            {
                "subtitles": {
                    "en": [{"ext": "srt", "name": "English"}]
                },
                "automatic_captions": {
                    "ja": [{"ext": "vtt", "name": "Japanese (auto)"}]
                }
            }
        """.trimIndent()

        val (manual, auto) = SubtitleParser.parseAllSubtitles(JSONObject(jsonStr))
        assertEquals(1, manual.size)
        assertEquals(1, auto.size)
        assertEquals(SubtitleType.MANUAL, manual[0].type)
        assertEquals(SubtitleType.AUTOMATIC, auto[0].type)
    }
}
