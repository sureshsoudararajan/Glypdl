package com.glypdl.android.ui.subtitles

import androidx.lifecycle.SavedStateHandle
import com.glypdl.android.data.model.SubtitleFile
import com.glypdl.android.data.repository.SettingsRepository
import com.glypdl.android.data.repository.SubtitleRepository
import io.mockk.coEvery
import io.mockk.coVerify
import io.mockk.every
import io.mockk.mockk
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.ExperimentalCoroutinesApi
import kotlinx.coroutines.flow.collect
import kotlinx.coroutines.flow.flowOf
import kotlinx.coroutines.launch
import kotlinx.coroutines.test.StandardTestDispatcher
import kotlinx.coroutines.test.advanceUntilIdle
import kotlinx.coroutines.test.resetMain
import kotlinx.coroutines.test.runTest
import kotlinx.coroutines.test.setMain
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Before
import org.junit.Test

@OptIn(ExperimentalCoroutinesApi::class)
class SubtitleManagementViewModelTest {

    private val testDispatcher = StandardTestDispatcher()
    private lateinit var subtitleRepository: SubtitleRepository
    private lateinit var settingsRepository: SettingsRepository

    private val sampleSubtitles = listOf(
        SubtitleFile(
            id = 1L,
            downloadId = "dl-1",
            mediaTitle = "Big Buck Bunny",
            mediaUrl = "https://example.com/bunny",
            languageCode = "en",
            languageName = "English",
            format = "srt",
            isAutoGenerated = false,
            contentUri = "content://media/sub/1",
            filePath = "/path/to/bunny.en.srt",
            fileName = "bunny.en.srt",
            fileSize = 1024L,
            createdAt = 1000L
        ),
        SubtitleFile(
            id = 2L,
            downloadId = "dl-1",
            mediaTitle = "Big Buck Bunny",
            mediaUrl = "https://example.com/bunny",
            languageCode = "es",
            languageName = "Spanish",
            format = "vtt",
            isAutoGenerated = true,
            contentUri = "content://media/sub/2",
            filePath = "/path/to/bunny.es.vtt",
            fileName = "bunny.es.vtt",
            fileSize = 2048L,
            createdAt = 2000L
        ),
        SubtitleFile(
            id = 3L,
            downloadId = "dl-2",
            mediaTitle = "Elephants Dream",
            mediaUrl = "https://example.com/elephants",
            languageCode = "fr",
            languageName = "French",
            format = "srt",
            isAutoGenerated = false,
            contentUri = "content://media/sub/3",
            filePath = "/path/to/elephants.fr.srt",
            fileName = "elephants.fr.srt",
            fileSize = 3072L,
            createdAt = 3000L
        )
    )

    @Before
    fun setup() {
        Dispatchers.setMain(testDispatcher)
        subtitleRepository = mockk(relaxed = true)
        settingsRepository = mockk(relaxed = true)

        every { subtitleRepository.getAllSubtitles() } returns flowOf(sampleSubtitles)
        every { subtitleRepository.getSubtitlesForDownload("dl-1") } returns flowOf(sampleSubtitles.take(2))
    }

    @After
    fun tearDown() {
        Dispatchers.resetMain()
    }

    @Test
    fun loadAllSubtitles_withoutDownloadId_displaysAll() = runTest {
        val savedStateHandle = SavedStateHandle()
        val viewModel = SubtitleManagementViewModel(savedStateHandle, subtitleRepository, settingsRepository)

        backgroundScope.launch { viewModel.uiState.collect() }
        advanceUntilIdle()

        val state = viewModel.uiState.value
        assertEquals(3, state.subtitles.size)
        assertEquals(3, state.filteredSubtitles.size)
    }

    @Test
    fun searchSubtitles_filtersByTitleAndLanguage() = runTest {
        val savedStateHandle = SavedStateHandle()
        val viewModel = SubtitleManagementViewModel(savedStateHandle, subtitleRepository, settingsRepository)

        backgroundScope.launch { viewModel.uiState.collect() }
        advanceUntilIdle()
        viewModel.onSearchQueryChanged("Spanish")
        advanceUntilIdle()

        val state = viewModel.uiState.value
        assertEquals(1, state.filteredSubtitles.size)
        assertEquals("Spanish", state.filteredSubtitles.first().languageName)
    }

    @Test
    fun filterByFormat_filtersAccurately() = runTest {
        val savedStateHandle = SavedStateHandle()
        val viewModel = SubtitleManagementViewModel(savedStateHandle, subtitleRepository, settingsRepository)

        backgroundScope.launch { viewModel.uiState.collect() }
        advanceUntilIdle()
        viewModel.onFormatFilterSelected("vtt")
        advanceUntilIdle()

        val state = viewModel.uiState.value
        assertEquals(1, state.filteredSubtitles.size)
        assertEquals("vtt", state.filteredSubtitles.first().format)
    }

    @Test
    fun deleteSubtitle_invokesRepository() = runTest {
        val savedStateHandle = SavedStateHandle()
        val viewModel = SubtitleManagementViewModel(savedStateHandle, subtitleRepository, settingsRepository)

        backgroundScope.launch { viewModel.uiState.collect() }
        coEvery { subtitleRepository.deleteSubtitle(1L, any()) } returns true

        viewModel.deleteSubtitle(1L)
        advanceUntilIdle()

        coVerify { subtitleRepository.deleteSubtitle(1L, true) }
    }
}
